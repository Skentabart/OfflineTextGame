def repeated_move(text):
    t=normalize(text); m=re.search(r'\b(\d+)\s*(?:раза?|раз)\b',t)
    if not m:return None,1
    count=max(1,min(10,int(m.group(1))))
    cleaned=(t[:m.start()]+' '+t[m.end():]).strip()
    return direction(cleaned),count

