def normalize(text):
    if not text:return ''
    t=str(text).lower().strip()
    for a,b in COMMON_REPLACEMENTS.items():t=t.replace(a,b)
    for canonical,forms in DIRECTION_FORMS.items():
        for form in sorted(forms,key=len,reverse=True):
            t=re.sub(rf'(?<![а-я]){re.escape(form)}(?![а-я])',canonical,t)
    t=t.replace('north','север').replace('south','юг').replace('east','восток').replace('west','запад')
    t=re.sub(r'\s+',' ',t); t=re.sub(r'[!?.,;:]+$','',t)
    return t.strip()

